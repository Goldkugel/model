"""
The answer store of a model: the prompts and answers of its histories in a
JSON file, so that an interrupted run can be resumed and answers that were
generated before are not generated again.

The file holds the settings the answers were generated with and the
histories as a tree by turn:

    {
      "format": 1,
      "settings": {"model": "google/medgemma-4b-it", "seed": 42, ...},
      "histories": {
        "<SHA-256 of the first prompt>": {
          "role": "user",
          "prompt": "...",
          "answer": {"text": "...", "reasoning": "...", "truncated": true},
          "next": {"<SHA-256 of the second prompt>": {...}}
        }
      }
    }

Every message that is not an answer (system and user prompts) is a node,
keyed by the SHA-256 of its text; the answer to a prompt is stored on its
node, and the following prompts under "next". Histories with the same
prompts therefore share their nodes: a turn that several histories share is
stored, and generated, once. A stored answer is only used if the history's
earlier answers are the stored ones, too, since an answer depends on them;
the turns stored after a prompt always followed the answer stored on it (or
no answer, for two prompts in a row), so a history is put back together
exactly as it was generated.

The answers depend on the settings of the model (see Model._answerSettings()),
so a file written with other settings is refused instead of being mixed
with answers of the current ones. Runs that share a file (e.g. the jobs of a
Slurm job array) merge their answers under a lock (see save()).
"""

from __future__ import annotations

import hashlib
import json
import os

from typing     import Optional

from logger     import Logger, lockedFile, writeJSON

from .ModelUtils import (
    messageRoleElement,
    messageTextElement,
    messageReasoningElement,
    messageTruncatedElement,
    modelRole,
    fileStamp,
)

# Version of the file layout, stored in the file
storeFormat = 1

# Keys of the file and of its nodes
formatKey    = "format"
settingsKey  = "settings"
historiesKey = "histories"
roleKey      = "role"
promptKey    = "prompt"
answerKey    = "answer"
nextKey      = "next"
# Keys of a stored answer
textKey      = "text"
reasoningKey = "reasoning"
truncatedKey = "truncated"


def promptKeyOf(text: str) -> str:
    """The key of a prompt in the store: the SHA-256 of its text."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _answerOf(message: dict) -> dict:
    """The stored form of an answer message."""
    answer = {textKey: str(message[messageTextElement])}
    if message.get(messageReasoningElement):
        answer[reasoningKey] = str(message[messageReasoningElement])
    if message.get(messageTruncatedElement):
        answer[truncatedKey] = True
    return answer


def _messageOf(answer: dict) -> dict:
    """The answer message of a stored answer."""
    message = {messageRoleElement: modelRole, messageTextElement: answer[textKey]}
    if answer.get(truncatedKey):
        message[messageTruncatedElement] = True
    if answer.get(reasoningKey):
        message[messageReasoningElement] = answer[reasoningKey]
    return message


def _turns(history: list[dict]) -> list[tuple[dict, Optional[dict]]]:
    """
    The (prompt, answer) pairs of a history: every message that is not an
    answer, with the answer following it (or None).
    """
    turns = []
    for message in history:
        if message.get(messageRoleElement) == modelRole and turns and turns[-1][1] is None:
            turns[-1] = (turns[-1][0], message)
        else:
            turns.append((message, None))
    return turns


def _merge(target: dict, source: dict) -> None:
    """
    Adds the nodes and answers of the tree `source` that `target` lacks to
    `target`. The following turns of a node are only merged if both trees
    have the same answer on it, since they depend on it: if the answers
    differ (e.g. generated by two runs at the same time), `target` keeps its
    answer and its turns, and those of `source` are left out.
    """
    for key, node in source.items():
        if key not in target:
            target[key] = node
            continue
        mine = target[key]
        if mine.get(answerKey) == node.get(answerKey):
            _merge(mine.setdefault(nextKey, {}), node.get(nextKey, {}))
        elif answerKey not in mine and not mine.get(nextKey):
            # Only the prompt was stored here (e.g. its answer was empty)
            mine[answerKey] = node[answerKey]
            mine[nextKey] = node.get(nextKey, {})


class AnswerStore:
    """
    The prompts and answers of a model in a JSON file (see the module
    documentation). load() reads the file, answerFor() looks up the stored
    answer to the last prompt of a history, add() stores the answers of
    histories, and save() writes the file.
    """

    def __init__(self, path: str, settings: dict):
        """
        :param path: Path of the JSON file; it is created by save().
        :param settings: The settings the answers depend on; a file written
            with other settings is refused by load() and save().
        """
        self.path: str = path
        self.settings: dict = settings
        self.tree: dict = {}
        # fileStamp() of the file as this store last read or wrote it, to
        # notice writes of other runs (see save())
        self.stamp: Optional[tuple] = None
        # Whether add() stored something since the last save()
        self.changed: bool = False

    def _read(self) -> dict:
        """
        Reads the tree of the file.

        :raises ValueError: If the file is not an answer store of this
            format, or was written with other settings.
        """
        with open(self.path, mode="r", encoding="utf-8") as f:
            data = json.load(f)

        if not isinstance(data, dict) or data.get(formatKey) != storeFormat:
            raise ValueError(
                f"'{self.path}' is not an answer store of format {storeFormat}; "
                f"delete it or use another file (prompt_tmp_file or setPostfix())."
            )

        # Through JSON, as the stored settings were, so e.g. tuples compare
        # equal to the lists they became
        current = json.loads(json.dumps(self.settings))
        stored  = data.get(settingsKey, {})
        differing = sorted(
            key for key in set(current) | set(stored)
            if current.get(key) != stored.get(key)
            # An unknown revision (model not in the local cache) is no
            # difference
            and not (key == "revision" and None in (current.get(key), stored.get(key)))
        )
        if differing:
            details = ", ".join(f"{key}: {stored.get(key)!r} -> {current.get(key)!r}" for key in differing)
            message = (
                f"The answers in '{self.path}' were generated with other settings ({details}). "
                f"Delete the file or use another one (prompt_tmp_file or setPostfix())."
            )
            # Logged as short rows; the exception keeps the whole message
            Logger().log(f"The answers in '{self.path}' were generated with other settings.")
            Logger().log(f"Differing settings: {details}.")
            Logger().log("Delete the file or use another one (prompt_tmp_file or setPostfix()).")
            raise ValueError(message)

        return data.get(historiesKey, {})

    def load(self) -> int:
        """
        Reads the file, if it exists.

        :return: Number of stored answers.
        :raises ValueError: See _read().
        """
        self.tree = {}
        self.stamp = None
        if os.path.isfile(self.path):
            self.tree = self._read()
            self.stamp = fileStamp(self.path)
        count = self.answerCount()
        Logger().log(f"Answer store '{os.path.basename(self.path)}': {count} stored answers.")
        return count

    def answerCount(self, tree: Optional[dict] = None) -> int:
        """The number of answers stored in `tree` (default: the store)."""
        tree = self.tree if tree is None else tree
        return sum(
            (answerKey in node) + self.answerCount(node.get(nextKey, {}))
            for node in tree.values()
        )

    def answerFor(self, history: list[dict]) -> Optional[dict]:
        """
        The stored answer to the last prompt of `history`, as an answer
        message, or None if there is none (or only an empty one), or if an
        earlier answer of the history is not the stored one.
        """
        tree = self.tree
        turns = _turns(history)
        for position, (prompt, answer) in enumerate(turns):
            node = tree.get(promptKeyOf(str(prompt[messageTextElement])))
            if node is None:
                return None
            if position == len(turns) - 1:
                stored = node.get(answerKey)
                if answer is not None or not stored or not stored.get(textKey):
                    return None
                return _messageOf(stored)
            # The following turns depend on this answer (or on there being
            # none, for two prompts in a row)
            if node.get(answerKey) != (_answerOf(answer) if answer is not None else None):
                return None
            tree = node.get(nextKey, {})
        return None

    def add(self, history: list[dict]) -> bool:
        """
        Stores the prompts and answers of `history`. Empty answers are not
        stored, so they are generated again.

        :return: Whether the history was stored; not if one of its earlier
            answers differs from the stored one (it was then generated with
            another context than the stored answers after it).
        """
        tree = self.tree
        for prompt, answer in _turns(history):
            text = str(prompt[messageTextElement])
            node = tree.setdefault(promptKeyOf(text), {
                roleKey: prompt.get(messageRoleElement),
                promptKey: text,
            })
            if answer is not None and str(answer[messageTextElement]):
                stored = _answerOf(answer)
                if answerKey not in node and not node.get(nextKey):
                    node[answerKey] = stored
                    self.changed = True
                elif node.get(answerKey) != stored:
                    # The stored turns after this prompt followed another
                    # answer (or none)
                    return False
            elif node.get(answerKey) is not None and answer is None:
                # Two prompts in a row, but the stored turns follow an answer
                return False
            tree = node.setdefault(nextKey, {})
        return True

    def save(self) -> None:
        """
        Writes the store to its file, atomically and under a lock. If another
        run wrote the file since this store read or wrote it, its answers are
        merged in first, so runs sharing the file do not lose each other's
        answers.

        :raises ValueError: If the file was written with other settings
            meanwhile (see _read()).
        """
        with lockedFile(self.path):
            current = fileStamp(self.path)
            if current is not None and current != self.stamp:
                _merge(self.tree, self._read())

            writeJSON({
                formatKey: storeFormat,
                settingsKey: self.settings,
                historiesKey: self.tree,
            }, self.path)
            self.stamp = fileStamp(self.path)
            self.changed = False
